/** Split a form into its marker flags and text. */
export function parseForm(form: string): { text: string; caseSensitive: boolean; strict: boolean } {
  if (form.startsWith("==")) return { text: form.slice(2), caseSensitive: true, strict: true };
  if (form.startsWith("=")) return { text: form.slice(1), caseSensitive: true, strict: false };
  return { text: form, caseSensitive: false, strict: false };
}

let cache: LexiconEntry[] | null = null;

/** The full lexicon, built once. */
export function getLexicon(): LexiconEntry[] {
  if (cache) return cache;
  const entries: LexiconEntry[] = [];
  for (const group of GROUPS) {
    for (const raw of group.entries) {
      const forms = raw.split("|").map((f) => f.trim()).filter(Boolean);
      entries.push({
        name: parseForm(forms[0]).text,
        category: group.category,
        domain: group.domain,
        forms,
      });
    }
  }
  cache = entries;
  return entries;
}
