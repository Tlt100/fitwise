/**
 * Curated skills lexicon.
 *
 * Each entry is written as a compact string: `"Canonical|alias|alias"`.
 *
 * - The first item is the canonical (display) name; the rest are aliases that
 *   count as the same skill ("k8s" -> Kubernetes, "Postgres" -> PostgreSQL).
 * - A leading `=` makes that form case-sensitive: it only matches when written
 *   exactly so. This is how words that are also ordinary English ("Excel",
 *   "Swift", "Spark", "Slack", "React") or short acronyms ("ML", "PM", "AI")
 *   avoid matching prose.
 * - A leading `==` is case-sensitive *and* strict: the form is also rejected at
 *   the start of a sentence when the next word is lower-case ("Go above and
 *   beyond"), or when glued to a hyphen ("Go-to-market", "C-suite"), or when
 *   directly followed by a period (a middle initial, "John R. Smith").
 *
 * Forms are compared after tokenisation and light stemming (see stem.ts), so
 * plurals and tenses do not need their own aliases. Keep every alias to at most
 * four tokens; the matcher looks at 1-4 token windows.
 *
 * Categories:
 *   hard - a skill or body of knowledge (a language, a method, a discipline)
 *   tool - a named product, platform, framework or library
 *   soft - an interpersonal or working-style skill
 *   cert - a certification, licence, clearance or degree
 */

export type TermCategory = "hard" | "soft" | "tool" | "cert";

export interface LexiconEntry {
  /** Canonical display name. */
  name: string;
  category: TermCategory;
  /** Broad field, for grouping and tests. */
  domain: string;
  /** Every form that counts, canonical first, with `=`/`==` markers kept. */
  forms: string[];
}

interface Group {
  domain: string;
  category: TermCategory;
  entries: string[];
}

